#!/usr/bin/env node
// Daily scan for ting_job_search. Costs no AI tokens.
//   1. builds the scanner config from profile/target-positions.md + my-sites.md
//   2. runs the Career-Ops scanner into data/scan/ (its own records, not Career-Ops')
//   3. ranks the new jobs you haven't seen, keeps the top N (default 40)
//   4. downloads each job ad's text and checks whether it is still open
// Output: data/candidates.json + data/jds/*.txt for the agent to score.
// Usage: node tools/scan.mjs [--top 40] [--skip-scan]
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { dump } from './yaml.mjs';
import { P, CAREER_OPS, careerOps, parseTargets, parseSites, buildPortals, readHistoryAdded, readSeen, preScore, locationRank, htmlToText, today } from './lib.mjs';

const argv = process.argv.slice(2);
const TOP = Number(argv[argv.indexOf('--top') + 1]) || 40;
const SKIP_SCAN = argv.includes('--skip-scan');
const JD_CAP = 6000;

function log(msg) { console.log(msg); }

async function fetchText(url, ms = 15000) {
  const res = await fetch(url, { redirect: 'follow', signal: AbortSignal.timeout(ms), headers: { 'user-agent': 'Mozilla/5.0 (Macintosh) ting_job_search' } });
  return { status: res.status, text: res.ok ? await res.text() : '' };
}

/** Job-ad text + open status, cheapest way first. */
export async function readJob(url, deps) {
  // 1. Known ATS APIs (Greenhouse, Lever, Ashby, Workable, SmartRecruiters, Workday)
  try {
    const live = await deps.checkLivenessViaApi(url);
    if (live?.result === 'expired') return { open: 'Closed', text: '' };
    const jd = await deps.fetchJdViaKnownApi(url);
    if (jd?.text) return { open: live?.result === 'active' ? 'Open' : 'Open (likely)', text: jd.text.slice(0, JD_CAP) };
  } catch { /* fall through */ }
  // 2. Platsbanken: public JobTech API by ad id
  const pb = url.match(/arbetsformedlingen\.se\/platsbanken\/annonser\/(\d+)/);
  if (pb) {
    try {
      const r = await fetchText(`https://jobsearch.api.jobtechdev.se/ad/${pb[1]}`);
      if (r.status === 404 || r.status === 410) return { open: 'Closed', text: '' };
      if (r.text) {
        const ad = JSON.parse(r.text);
        const text = [ad.headline, ad.employer?.name, ad.workplace_address?.municipality, ad.description?.text].filter(Boolean).join('\n');
        const closed = ad.removed || (ad.application_deadline && Date.parse(ad.application_deadline) < Date.now());
        return { open: closed ? 'Closed' : 'Open', text: text.slice(0, JD_CAP) };
      }
    } catch { /* fall through */ }
  }
  // 3. Any other page: plain HTTP, strip the HTML
  try {
    const r = await fetchText(url);
    if (r.status === 404 || r.status === 410) return { open: 'Closed', text: '' };
    const text = htmlToText(r.text).slice(0, JD_CAP);
    return { open: text.length > 400 ? 'Open (likely)' : 'Check by hand', text };
  } catch (e) {
    return { open: 'Check by hand', text: '' };
  }
}

async function main() {
  const targets = parseTargets(fs.readFileSync(P.targets, 'utf8'));
  const sites = parseSites(fs.readFileSync(P.sites, 'utf8'));
  fs.mkdirSync(path.join(P.scanRoot, 'data'), { recursive: true });
  fs.writeFileSync(P.portals, '# Generated by tools/scan.mjs from my-sites.md and profile/target-positions.md. Do not edit.\n' + dump(buildPortals(targets, sites)));
  log(`Sites: ${sites.companies.filter(c => c.scan).length} companies, ${sites.boards.filter(b => b.scan).map(b => b.name).join(', ')}`);

  if (!SKIP_SCAN) {
    log('Scanning (no AI tokens)…');
    const r = spawnSync(process.execPath, [path.join(CAREER_OPS, 'scan.mjs')], {
      cwd: CAREER_OPS, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024,
      env: { ...process.env, CAREER_OPS_DATA_DIR: P.scanRoot, CAREER_OPS_PORTALS: P.portals },
    });
    fs.writeFileSync(path.join(P.scanRoot, 'last-scan.log'), (r.stdout || '') + '\n' + (r.stderr || ''));
    if (r.status !== 0 && r.status !== null) log(`Scanner finished with code ${r.status}; details in data/scan/last-scan.log`);
  }

  const seen = readSeen();
  const fresh = readHistoryAdded().filter(j => j.url && !seen.has(j.url));
  const ranked = fresh
    .map(j => ({ ...j, preScore: preScore(j, targets), locRank: locationRank(j.location, targets) }))
    .sort((a, b) => b.preScore - a.preScore)
    .slice(0, TOP);
  log(`New jobs not seen before: ${fresh.length}. Reading the top ${ranked.length} job ads…`);

  const deps = {
    ...(await careerOps('liveness-api.mjs')),
    ...(await careerOps('browser-extract.mjs')),
  };
  fs.mkdirSync(P.jds, { recursive: true });
  const out = [];
  for (let i = 0; i < ranked.length; i++) {
    const j = ranked[i];
    const id = `${today().replace(/-/g, '')}-${String(i + 1).padStart(2, '0')}`;
    const { open, text } = await readJob(j.url, deps);
    const jdFile = text ? path.join('data', 'jds', `${id}.txt`) : '';
    if (text) fs.writeFileSync(path.join(P.jds, `${id}.txt`), `${j.title}\n${j.company} · ${j.location}\n${j.url}\n\n${text}\n`);
    out.push({ id, found: j.found, company: j.company, title: j.title, location: j.location, url: j.url, source: j.source, open, jdFile, preScore: j.preScore });
  }
  fs.writeFileSync(P.candidates, JSON.stringify({ date: today(), candidates: out }, null, 1));
  fs.writeFileSync(P.scores, '{}\n');
  const manual = sites.companies.filter(c => c.scan && !/greenhouse|lever\.co|ashbyhq|teamtailor|workable|smartrecruiters|recruitee|personio|bamboohr|myworkdayjobs|jobs\.gem\.com|breezy|jobylon|join\.com|pinpoint|rippling|comeet|softgarden/i.test(c.url) && !c.provider);
  log(`Ready: ${out.length} jobs in data/candidates.json (${out.filter(c => c.jdFile).length} with job-ad text, ${out.filter(c => c.open === 'Closed').length} already closed).`);
  if (manual.length) log(`Not read automatically (check by hand if you want): ${manual.map(c => c.name).join(', ')}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch(e => { console.error(e); process.exit(1); });
